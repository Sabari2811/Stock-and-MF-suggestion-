from __future__ import annotations

from datetime import date, datetime
from typing import Protocol, Sequence

from app.core.models import GlobalContext, Quote, SectorSnapshot, StockSnapshot


class MarketDataProvider(Protocol):
    def list_symbols(self, exchange: str) -> Sequence[str]: ...
    def get_quotes(self, symbols: Sequence[str], exchange: str) -> Sequence[Quote]: ...
    def get_snapshots(self, symbols: Sequence[str], exchange: str, timeframe: str) -> Sequence[StockSnapshot]: ...
    def get_ohlcv(self, symbol: str, exchange: str, timeframe: str, start: date, end: date): ...


class MarketContextProvider(Protocol):
    def get_context(self) -> GlobalContext: ...
    def get_sectors(self) -> Sequence[SectorSnapshot]: ...


class NewsProvider(Protocol):
    def get_stock_news(self, symbols: Sequence[str], since: datetime | None = None): ...
    def get_global_news(self, since: datetime | None = None): ...
